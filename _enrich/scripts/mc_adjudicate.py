#!/usr/bin/env python3
"""Rebuild `adjudication.md` and `consensus.csv` for the 100-item double-coded overlap.

    python mc_adjudicate.py                     # working copy, in place
    python mc_adjudicate.py --in DIR --out DIR  # e.g., an unpacked coding.zip

Accepts both raw endpoint URLs (working copy) and integer surrogate keys
(`endpoint_group`, `host_group` in the deposit).
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
CODING = ROOT / "_enrich" / "coding"

# Human decision taken on 2026-08-20 for every disputed item; see the journal text.
CONSENSUS_LABEL = "0"
CONSENSUS_NOTE = (
    "HTML SPA shell, no agent-card/MCP/A2A in the saved body; "
    "rubric, Border cases: website/landing → 0"
)


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def host_of(url: str) -> str:
    return urlsplit(url).hostname or url


def host_tally(items: list[dict], prefix: str = "") -> str:
    counts: dict[str, int] = {}
    for d in items:
        counts[d["host"]] = counts.get(d["host"], 0) + 1
    ordered = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
    return ", ".join(f"{prefix}{h} ({n})" for h, n in ordered)


def run(in_dir: Path, out_dir: Path) -> None:
    sheet = read_csv(in_dir / "coding_sheet.csv")
    first = sheet[0] if sheet else {}
    key = "endpoint_group" if "endpoint_group" in first else "endpoint"
    host_col = "host_group" if "host_group" in first else ("host" if "host" in first else None)
    ep2host = {r[key]: (r[host_col] if host_col else host_of(r[key])) for r in sheet}
    idx2ep = {int(r["idx"]): r[key] for r in sheet}
    ep2ct = {r[key]: (r["content_type"] or "").lower() for r in sheet}
    ep2stratum = {r[key]: r["stratum"] for r in read_csv(in_dir / "sample.csv")}

    overlap = json.loads((in_dir / "overlap_idx.json").read_text(encoding="utf-8"))["idx"]
    c1 = {r[key]: r["label"].strip() for r in read_csv(in_dir / "coder_1.csv")}
    c2 = {r[key]: r["label"].strip() for r in read_csv(in_dir / "coder_2.csv")}

    disputed: list[dict] = []
    for i in overlap:
        ep = idx2ep[i]
        a, b = c1[ep], c2[ep]
        if a != b:
            disputed.append({
                "idx": i, "endpoint": ep, "c1": a, "c2": b,
                "stratum": ep2stratum[ep], "host": ep2host[ep],
            })

    # The written decision below only holds for stratum-B HTML bodies; refuse to emit a
    # journal that no longer matches the data it describes.
    off_spec = [d for d in disputed
                if d["stratum"] != "B" or not ep2ct[d["endpoint"]].startswith("text/html")
                or d["c1"] != "0"]
    if off_spec:
        raise SystemExit(f"disputed items outside the recorded decision: {off_spec}")

    grp_u = [d for d in disputed if d["c2"] == "U"]
    grp_1 = [d for d in disputed if d["c2"] == "1"]
    if len(grp_u) + len(grp_1) != len(disputed):
        raise SystemExit("unexpected coder2 labels among the disputed items")

    b_overlap = [i for i in overlap if ep2stratum[idx2ep[i]] == "B"]
    b_u = [i for i in b_overlap if c2[idx2ep[i]] == "U"]
    u_share = 100.0 * len(b_u) / len(b_overlap)

    by_host: dict[str, list[int]] = {}
    for d in disputed:
        by_host.setdefault(d["host"], []).append(d["idx"])
    top_host, top_idxs = max(by_host.items(), key=lambda kv: (len(kv[1]), kv[0]))
    host_prefix = "host_group " if host_col == "host_group" else ""
    host_hdr = "host_groups" if host_col == "host_group" else "hosts"
    top_line = (
        f"Largest host group (host_group {top_host}, {len(top_idxs)} items): "
        f"{', '.join(str(i) for i in top_idxs)}."
        if host_col == "host_group"
        else f"{top_host} indices ({len(top_idxs)} items): {', '.join(str(i) for i in top_idxs)}."
    )
    rows_md = [
        f"| idx | stratum | coder1 | coder2 | consensus | {'URL' if key == 'endpoint' else key} |",
        "|---:|:---:|:---:|:---:|:---:|---|",
    ]
    for d in disputed:
        rows_md.append(
            f"| {d['idx']} | {d['stratum']} | {d['c1']} | {d['c2']} "
            f"| **{CONSENSUS_LABEL}** | `{d['endpoint']}` |"
        )
    grp_1_ids = "; ".join(f"{host_prefix}{d['host']} #{d['idx']}" for d in grp_1)

    md = f"""# Adjudication — 100-item overlap (mc_t2)

Date: 2026-08-20. Coder 1 — project owner (300 items). Coder 2 — second human coder
(the 100 overlap items). Raw labels are never rewritten: `coder_1.csv`, `coder_2.csv`.
The dispute outcome lives in this journal and in `consensus.csv`. This file is
regenerated by `mc_adjudicate.py` from the raw labels shipped in the deposit.

## Decision

All **{len(disputed)}** disagreements are stratum B, Content-Type `text/html`, body an SPA
shell (Next.js / loader JS). The saved 2 KB contain no MCP / A2A agent-card / ERC-8004
registration / OASF.

**Consensus label for all {len(disputed)}: `{CONSENSUS_LABEL}` (not_agent).**

Basis — rubric `CODING_RUBRIC.md`, "Border cases":

- "HTML page of a website or a landing page" → 0;
- border case "project landing page whose HTML mentions `\"a2a\"`" → 0;
- U is allowed only when *this body* does not permit a decision (mid-token truncation with
  no signal, binary, auth wall). Here the signal is present: this is HTML, not a machine
  interface.

Coder 1 labeled all of them 0 — the consensus matches coder 1. Validation-sample
statistics are **not recomputed**.

## Classes

| Class | n | coder1 | coder2 | {host_hdr} | consensus |
|---|---:|:---:|:---:|---|:---:|
| HTML SPA, coder2 = U | {len(grp_u)} | 0 | U | {host_tally(grp_u, host_prefix)} | {CONSENSUS_LABEL} |
| HTML SPA, coder2 = 1 | {len(grp_1)} | 0 | 1 | {grp_1_ids} | {CONSENSUS_LABEL} |

The `coder2 = 1` items are the same kind of body as the U group: a profile / marketplace
page, not an agent endpoint. Coder 2's label 1 here is a rubric-application error (a
website taken for an interface), not a signal in the body.

## Deviation from the U-share gate

Coder 2's U share in stratum B on the overlap is {len(b_u)}/{len(b_overlap)} = {u_share:.0f}%
(10% gate FAIL). The protocol prescribes stopping the coding and enlarging the body
snapshot. **The snapshot was not enlarged.** Reason: all {len(b_u)} U items are SPA shells;
enlarging 2 KB of a Next.js loader will not add an agent-card. This is a
rubric-interpretation issue, not a defect of the snapshot parameter. After consensus, U on
the overlap = 0. The deviation is logged here with its date, as the protocol header
requires.

Rubric clarification (for the paper text; the rules themselves are unchanged): *an HTML SPA
with no machine-readable agent object in the saved body → 0, not U. U is for when the
visible part cannot distinguish a protocol response from anything else (truncated JSON,
binary, empty auth response).*

## Items

{chr(10).join(rows_md)}

{top_line}
"""

    (out_dir / "adjudication.md").write_text(md, encoding="utf-8")

    grouped = key != "endpoint"
    disp = {d["idx"] for d in disputed}
    with (out_dir / "consensus.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        out_host_col = host_col or "host"
        head = ["idx", key] + ([out_host_col] if grouped else [])
        w.writerow(head + ["coder1", "coder2", "consensus", "source", "note"])
        for i in overlap:
            ep = idx2ep[i]
            a, b = c1[ep], c2[ep]
            lead = [i, ep] + ([ep2host[ep]] if grouped else [])
            if i in disp:
                w.writerow(lead + [a, b, CONSENSUS_LABEL, "adjudicated", CONSENSUS_NOTE])
            else:
                if a != b or a not in ("0", "1"):
                    raise SystemExit(f"idx {i}: non-disputed row is not a clean 0/1 agreement")
                w.writerow(lead + [a, b, a, "agreed", ""])

    print(f"wrote adjudication.md  disputed={len(disp)} agreed={len(overlap) - len(disp)}")
    print("wrote consensus.csv")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="src", type=Path, default=CODING,
                    help="directory holding the coding layer (default: the working copy)")
    ap.add_argument("--out", dest="dst", type=Path, default=None,
                    help="where to write adjudication.md and consensus.csv (default: --in)")
    args = ap.parse_args()
    run(args.src, args.dst or args.src)


if __name__ == "__main__":
    main()
